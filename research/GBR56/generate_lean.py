"""Generate short proper-factor certificates for the finite radius examples."""
from math import isqrt
from pathlib import Path
import json

BASE=Path(__file__).parent
ROOT=BASE.parents[1]


def proper_factor(n):
    return next((d for d in range(2,isqrt(n)+1) if n%d==0),None)


def main():
    data=json.loads((BASE/'noncentral_results.json').read_text())
    names={4:'four',8:'eight',16:'sixteen',32:'thirtyTwo',64:'sixtyFour',128:'oneTwentyEight'}
    source='''import GoldbachDeltaInduction.OffsetFactorCertificate

namespace GoldbachDeltaInduction

def FiniteAdjacentPrimes (p q : ℕ) : Prop :=
  p.Prime ∧ q.Prime ∧ p<q ∧ ∀ r ∈ Finset.Ioo p q, ¬r.Prime

instance (p q : ℕ) : Decidable (FiniteAdjacentPrimes p q) :=
  inferInstanceAs (Decidable
    (p.Prime ∧ q.Prime ∧ p<q ∧ ∀ r ∈ Finset.Ioo p q, ¬r.Prime))

theorem finiteAdjacent_iff (p q : ℕ) :
    FiniteAdjacentPrimes p q ↔ AdjacentPrimes p q := by
  simp only [FiniteAdjacentPrimes,AdjacentPrimes,Finset.mem_Ioo]
  aesop

def ExactOffsetMinimum (c delta : ℕ) : Prop :=
  SymmetricPrimePair c delta ∧ ∀ e ∈ Finset.range delta, ¬SymmetricPrimePair c e

set_option maxRecDepth 8192
set_option maxHeartbeats 2000000

/-! Generated by research/GBR56/generate_lean.py. Each list supplies a proper
factor for one endpoint at EVERY smaller offset, including zero. The data
are not trusted: the kernel checks the finite divisibility certificate. -/
'''
    certificates=[]
    for C,name in names.items():
        row=data['first_counterexamples_to_delta_le_Ck'][str(C)]
        p,q,k,c,d=(row[key] for key in ('p','q','k','c','delta'))
        factors=[]
        for e in range(d):
            f=proper_factor(c-e) or proper_factor(c+e)
            assert f is not None
            assert 1<f and ((f<c-e and (c-e)%f==0) or (f<c+e and (c+e)%f==0))
            factors.append(f)
        entries=', '.join(map(str,factors))
        source+=f'''
theorem radius_{name}_fails :
    AdjacentPrimes {p} {q} ∧ ExactOffsetMinimum {c} {d} ∧ {C}*{k}<{d} := by
  let factors : List ℕ := [{entries}]
  have hc : OffsetFactorCertificate {c} {d} factors := by decide
  have hadj : AdjacentPrimes {p} {q} := by
    refine ⟨by norm_num,by norm_num,by norm_num,?_⟩
    intro r hrlo hrhi
    interval_cases r <;> norm_num
  exact ⟨hadj,
    ⟨by norm_num [SymmetricPrimePair],factor_certificate_excludes hc⟩,by decide⟩
'''
        certificates.append(dict(C=C,**row,factors=factors))
    source+='\nend GoldbachDeltaInduction\n'
    (ROOT/'GoldbachDeltaInduction/OffsetRadiusExamples.lean').write_text(source)
    (BASE/'factor_certificates.json').write_text(json.dumps(certificates,indent=2)+'\n')
    print(json.dumps(dict(certificates=len(certificates),excluded_offsets=sum(len(c['factors']) for c in certificates))))


if __name__=='__main__':
    main()
